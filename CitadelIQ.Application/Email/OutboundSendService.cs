using CitadelIQ.Application.Accounts;
using CitadelIQ.Application.Interfaces;
using CitadelIQ.Application.Options;
using CitadelIQ.Domain.Entities;
using CitadelIQ.Domain.Enums;
using Microsoft.Extensions.Logging;
using Microsoft.Extensions.Options;

namespace CitadelIQ.Application.Email;

/// <summary>
/// Sends one queued email, in a scope that has entered the outbound row's workspace. Duplicate-safe (decision 18):
/// the row is marked Sending and committed before SMTP; a row found in Sending again (a crash or an SMTP failure) is
/// first looked up in the Sent folder by its pre-generated Message-ID. The recipient is re-read and re-checked here,
/// so a member who left before an admin sent their draft gets nothing.
/// </summary>
public class OutboundSendService(
    IWorkspaceContext workspaceContext,
    IOutboundEmailRepository outbound,
    IOutboundEmailQueue queue,
    IUserAccountRepository users,
    IMembershipRepository memberships,
    IMailbox mailbox,
    IMailSender sender,
    IUnitOfWork unitOfWork,
    IOptionsMonitor<EmailAgentOptions> options,
    ILogger<OutboundSendService> logger)
{
    public const string RecipientInactive = "RecipientInactive";
    public const string NotificationsOff = "NotificationsOff";
    public const string SendLimit = "SendLimit";
    public const string AutoRepliesPaused = "AutoRepliesPaused";

    public async Task SendAsync(OutboundClaim claim, CancellationToken cancellationToken = default)
    {
        RequireWorkspace(claim);
        var email = await outbound.GetByIdAsync(claim.OutboundEmailId, cancellationToken);
        if (email is null || email.IsFinished)
        {
            await queue.MarkDoneAsync(claim.OutboundEmailId, null, cancellationToken); // removed by retention, or already handled
            return;
        }

        if (email.Status == OutboundEmailStatus.Sending && await mailbox.SentFolderContainsAsync(email.MessageId, cancellationToken))
        {
            await FinishAsync(email, sent: true, cancellationToken);
            logger.LogInformation("Outbound email {OutboundEmailId} found in the Sent folder; not resent", email.Id);
            return;
        }

        var o = options.CurrentValue;
        var user = await users.GetByIdAsync(email.ToUserId, cancellationToken);
        var membership = await memberships.GetByUserIdAsync(email.ToUserId, cancellationToken);
        var cancelReason =
            user is null || user.IsClosed || string.IsNullOrWhiteSpace(user.Email) || membership?.WorkspaceId != email.WorkspaceId
                ? RecipientInactive
            : email.Kind == OutboundEmailKind.DraftNotification && (membership.Role < WorkspaceRole.Admin || !membership.EmailDraftNotifications)
                ? NotificationsOff
            : o.Mode != EmailAgentMode.On && email.Kind is OutboundEmailKind.AutoReply or OutboundEmailKind.NoConfidentReply
                ? AutoRepliesPaused // the kill switch was turned down after this answer was queued
            : await queue.CountSentSinceAsync(DateTimeOffset.UtcNow.AddDays(-1), cancellationToken) >= o.Limits.MaxSentPerDay
                ? SendLimit
                : null;

        if (cancelReason == SendLimit && email.Kind == OutboundEmailKind.DraftReply)
        {
            // A person wrote this reply and was told it was sent: wait for the rolling window instead of dropping it.
            await queue.ScheduleRetryAsync(email.Id, DateTimeOffset.UtcNow.AddMinutes(15), cancellationToken);
            logger.LogWarning("Outbound email {OutboundEmailId} deferred: daily send limit reached", email.Id);
            return;
        }

        if (cancelReason is not null)
        {
            email.Cancel(cancelReason);
            await FinishAsync(email, sent: false, cancellationToken);
            logger.LogInformation("Outbound email {OutboundEmailId} cancelled: {Reason}", email.Id, cancelReason);
            return;
        }

        // Committed before the SMTP call: after a crash the row says "Sending" and the Sent folder is checked first.
        email.MarkSending();
        await outbound.UpdateAsync(email, cancellationToken);

        await sender.SendAsync(new OutboundMessage(
            email.MessageId,
            user!.Email,
            user.DisplayName,
            email.Subject,
            email.Body,
            email.InReplyTo,
            (email.References ?? "").Split(' ', StringSplitOptions.RemoveEmptyEntries),
            email.Kind switch
            {
                OutboundEmailKind.DraftNotification => OutboundAutomation.AutoGenerated,
                OutboundEmailKind.DraftReply => OutboundAutomation.None,
                _ => OutboundAutomation.AutoReplied
            }), cancellationToken);

        await FinishAsync(email, sent: true, CancellationToken.None);
        logger.LogInformation("Outbound email {OutboundEmailId} ({Kind}) sent on attempt {Attempt}", email.Id, email.Kind, claim.Attempt);
    }

    /// <summary>The retries ran out: the activity list shows "Reply could not be delivered".</summary>
    public async Task MarkFailedAsync(OutboundClaim claim, CancellationToken cancellationToken = default)
    {
        RequireWorkspace(claim);
        var email = await outbound.GetByIdAsync(claim.OutboundEmailId, cancellationToken);
        if (email is not null)
        {
            email.MarkFailed();
            await FinishAsync(email, sent: false, cancellationToken);
        }
        else
        {
            await queue.MarkDoneAsync(claim.OutboundEmailId, null, cancellationToken);
        }

        logger.LogWarning("Outbound email {OutboundEmailId} failed after {Attempts} attempts", claim.OutboundEmailId, claim.Attempt);
    }

    private Task FinishAsync(OutboundEmail email, bool sent, CancellationToken cancellationToken) =>
        unitOfWork.ExecuteInTransactionAsync(async () =>
        {
            if (sent)
            {
                email.MarkSent();
            }

            await outbound.UpdateAsync(email, cancellationToken);
            await queue.MarkDoneAsync(email.Id, sent ? email.SentAtUtc : null, cancellationToken);
        }, cancellationToken);

    private void RequireWorkspace(OutboundClaim claim)
    {
        if (workspaceContext.WorkspaceId != claim.WorkspaceId)
        {
            throw new InvalidOperationException("Enter the outbound email's workspace before sending it.");
        }
    }
}
