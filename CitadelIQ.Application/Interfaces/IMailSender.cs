namespace CitadelIQ.Application.Interfaces;

/// <summary>How a sent message marks itself (RFC 3834 <c>Auto-Submitted</c>).</summary>
public enum OutboundAutomation
{
    None,
    AutoReplied,
    AutoGenerated
}

/// <summary>A plain-text email from the support address. Message-IDs are without angle brackets.</summary>
public record OutboundMessage(
    string MessageId,
    string To,
    string? ToDisplayName,
    string Subject,
    string Body,
    string? InReplyTo,
    IReadOnlyList<string> References,
    OutboundAutomation Automation);

/// <summary>Sends from the support address (SMTP). Throws <see cref="Common.MailboxUnavailableException"/> on failure.</summary>
public interface IMailSender
{
    Task SendAsync(OutboundMessage message, CancellationToken cancellationToken = default);
}
